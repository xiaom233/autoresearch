print(f"Time budget: {TIME_BUDGET}s  Batch: {BATCH_SIZE}  LR: {LEARNING_RATE}")

# ---------------------------------------------------------------------------
# LR schedule
# ---------------------------------------------------------------------------

def get_lr_multiplier(step, total_steps):
    if step < WARMUP_STEPS:
        return step / max(1, WARMUP_STEPS)
    if LR_SCHEDULE == "cosine":
        progress = (step - WARMUP_STEPS) / max(1, total_steps - WARMUP_STEPS)
        return 0.5 * (1 + math.cos(math.pi * progress))
    return 1.0

# ---------------------------------------------------------------------------
# Training loop
# ---------------------------------------------------------------------------

t_start_training = time.time()
smooth_loss = 0
total_training_time = 0
step = 0
best_psnr = 0
best_val_psnr = 0

while True:
    torch.cuda.synchronize()
    t0 = time.time()

    # Forward + backward
    with autocast_ctx:
        pred = model(x)
        loss = F.l1_loss(pred, y)

    loss.backward()

    # LR update
    lrm = get_lr_multiplier(step, max(step + 1, 1000))
    for group in optimizer.param_groups:
        group["lr"] = LEARNING_RATE * lrm

    optimizer.step()
    optimizer.zero_grad(set_to_none=True)

    # Fetch next batch
    x, y, epoch = next(train_loader)
    x, y = x.to(device, non_blocking=True), y.to(device, non_blocking=True)

    torch.cuda.synchronize()
    t1 = time.time()
    dt = t1 - t0

    # Skip warmup steps for timing
    if step > 5:
        total_training_time += dt

    # Logging
    loss_f = loss.item()
    ema_beta = 0.95
    smooth_loss = ema_beta * smooth_loss + (1 - ema_beta) * loss_f
    debiased_loss = smooth_loss / (1 - ema_beta ** (step + 1))

    if step % LOG_INTERVAL == 0:
        with torch.no_grad(), autocast_ctx:
            train_psnr = compute_psnr(pred.float(), y)
            best_psnr = max(best_psnr, train_psnr)

    if step > 0 and step % VAL_INTERVAL == 0:
        val_psnr = evaluate(model, val_loader, device, autocast_ctx)
        best_val_psnr = max(best_val_psnr, val_psnr)
        print(f"\n  [Val @ step {step}] PSNR: {val_psnr:.2f} dB  (best: {best_val_psnr:.2f})")

    progress = min(total_training_time / TIME_BUDGET, 1.0)
    pct = 100 * progress
    remaining = max(0, TIME_BUDGET - total_training_time)
    imgs_per_sec = int(BATCH_SIZE / dt) if dt > 0 else 0

    print(f"\rstep {step:05d} ({pct:.1f}%) | loss: {debiased_loss:.6f} | lr: {LEARNING_RATE * lrm:.2e} | "
          f"psnr: {best_psnr:.2f}dB | dt: {dt*1000:.0f}ms | imgs/s: {imgs_per_sec} | "
          f"epoch: {epoch} | rem: {remaining:.0f}s    ", end="", flush=True)

    # GC management
    if step == 0:
        gc.collect()
        gc.freeze()
        gc.disable()
    elif (step + 1) % 5000 == 0:
        gc.collect()

    step += 1

    if step > 10 and total_training_time >= TIME_BUDGET:
        break

print()

