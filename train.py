class ValDataset:
    """Load validation images from disk, center-crop, apply degradation.

    Returns (degraded, clean) float32 tensors in [0, 1], shape [3, H, W].
    """

    def __init__(self, val_dir, crop_size=256, count=None, params_path=None):
        self.img_paths = sorted(scandir(val_dir, full_path=True))
        if count:
            self.img_paths = self.img_paths[:count]
        self.crop_size = crop_size
        self.pipeline = load_degradation_params(params_path) if params_path else []

    def __len__(self):
        return len(self.img_paths)

    def __getitem__(self, idx):
        img = np.array(Image.open(self.img_paths[idx]).convert("RGB"), dtype=np.uint8)
        h, w = img.shape[:2]
        # Center crop
        top = max(0, (h - self.crop_size) // 2)
        left = max(0, (w - self.crop_size) // 2)
        img = img[top:top + self.crop_size, left:left + self.crop_size]

        clean = img.copy()
        for func_name, severity in self.pipeline:
            img = add_distortion(img, severity=severity, distortion_name=func_name)

        degraded_t = torch.from_numpy(img).permute(2, 0, 1).float() / 255.0
        clean_t = torch.from_numpy(clean).permute(2, 0, 1).float() / 255.0
        return degraded_t, clean_t


@torch.no_grad()
def evaluate(model, val_loader, device, autocast_ctx):
    """Compute average PSNR over validation set."""
    model.eval()
    psnr_sum = 0.0
    count = 0
    for degraded, clean in val_loader:
        degraded = degraded.to(device)
        clean = clean.to(device)
        with autocast_ctx:
            pred = model(degraded)
        psnr_sum += compute_psnr(pred.float(), clean)
        count += 1
    model.train()
    return psnr_sum / count if count else 0.0


# ---------------------------------------------------------------------------
# Metrics
# ---------------------------------------------------------------------------

def compute_psnr(pred, target):
    """PSNR in dB. Assumes pixel values in [0, 1]."""
    mse = F.mse_loss(pred, target)
    if mse == 0:
        return 100.0
    return 20 * math.log10(1.0) - 10 * math.log10(mse.item())


