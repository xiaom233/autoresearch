#!/usr/bin/env python3
"""Aggregate E6-A agent run-to-run variance (18 R0-only runs, fixed support/seed)."""
import glob
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
E6A = ROOT / "rebuttal_runs/E6_A"
SCENARIOS = ["blind_0006", "blind_0008", "blind_0010",
             "blind_0013", "blind_0017", "blind_0024"]


def pipe_key(p):
    if not p:
        return []
    if isinstance(p[0], dict):
        return [(x["function"], int(x["severity"])) for x in p]
    return [(x[0], int(x[1])) for x in p]


def load_rows():
    rows = []
    for p in glob.glob(str(E6A / "test_metrics_gpu*.jsonl")):
        rows += [json.loads(l) for l in open(p) if l.strip()]
    return rows


def main():
    sel = {r["run_id"]: r for r in map(json.loads, open(E6A / "selection.jsonl"))}
    rows = load_rows()
    by_run = defaultdict(lambda: defaultdict(list))
    for r in rows:
        by_run[r["run_id"]][r["dataset"]].append(r["psnr_rgb"])

    e6b = json.load(open(ROOT / "rebuttal_runs/E6/e6_summary.json"))
    e6b_set1 = {sid: e6b["scenarios"][sid]["set1"]["datasets"]["DIV2K"]["psnr"]
                for sid in SCENARIOS}

    out = {"scenarios": {}, "macro": {}, "n_metrics": len(rows),
           "scope_notes": [
               "E6-A: 18 runs = 6 scenarios x 3 agent repetitions; per repetition the agent re-ran blind ID on the same 5 support pairs, training uses the repeated fixed seed (42) and fixed Swin+SG/Direct config.",
               "E6-A is R0-only (no R0->R1/R2 reflection); E6-B used the full rule controller R0-R2.",
               "Test is the GT-LQ DIV2K 100 / LSDIR 250 set generated by eval_checkpoint.py test (seed-salt v1), same protocol as E6-B.",
               "Run-to-run spread here mixes blind-ID stochasticity only; training is deterministic given the predicted pipeline.",
           ]}

    for sid in SCENARIOS:
        gt = pipe_key(json.load(open(ROOT / f"exp41/degradation_gt/{sid}_params.json"))["pipeline"])
        rec = {"gt_pipeline": gt, "reps": {}, "pipeline_match": {}}
        dv, ls = [], []
        pipes = []
        for rep in [1, 2, 3]:
            run_id = f"E6A_{sid}_rep{rep}"
            if run_id not in sel:
                rec["reps"][f"rep{rep}"] = None
                continue
            s = sel[run_id]
            pred = [tuple(x) for x in s["predicted_pipeline"]]
            pipes.append(tuple(pred))
            rec["pipeline_match"][f"rep{rep}"] = pred == gt
            d = by_run[run_id].get("DIV2K")
            l = by_run[run_id].get("LSDIR")
            entry = {
                "predicted_pipeline": [list(x) for x in pred],
                "verdict": s.get("predicted_verdict"),
                "ci": s.get("predicted_ci"),
                "support_psnr": s.get("support_psnr"),
                "checkpoint_step": s.get("checkpoint_step"),
                "DIV2K": float(np.mean(d)) if d else None,
                "LSDIR": float(np.mean(l)) if l else None,
                "n_DIV2K": len(d or []), "n_LSDIR": len(l or []),
            }
            rec["reps"][f"rep{rep}"] = entry
            if d:
                dv.append(entry["DIV2K"])
            if l:
                ls.append(entry["LSDIR"])
        rec["DIV2K"] = {"mean": float(np.mean(dv)) if dv else None,
                        "sd": float(np.std(dv, ddof=1)) if len(dv) > 1 else None,
                        "range": float(max(dv) - min(dv)) if dv else None}
        rec["LSDIR"] = {"mean": float(np.mean(ls)) if ls else None,
                        "sd": float(np.std(ls, ddof=1)) if len(ls) > 1 else None,
                        "range": float(max(ls) - min(ls)) if ls else None}
        rec["n_unique_pipelines"] = len(set(pipes))
        rec["exact_gt_matches"] = int(sum(rec["pipeline_match"].values()))
        rec["e6b_set1_DIV2K"] = e6b_set1[sid]
        out["scenarios"][sid] = rec

    for ds in ["DIV2K", "LSDIR"]:
        means = [out["scenarios"][s][ds]["mean"] for s in SCENARIOS
                 if out["scenarios"][s][ds]["mean"] is not None]
        out["macro"][ds] = {"mean_of_scenario_means": float(np.mean(means)),
                            "scenario_sd": float(np.std(means, ddof=1)),
                            "n_scenarios": len(means)}
    out["macro"]["mean_within_scenario_sd"] = {
        ds: float(np.mean([out["scenarios"][s][ds]["sd"] for s in SCENARIOS
                           if out["scenarios"][s][ds]["sd"] is not None]))
        for ds in ["DIV2K", "LSDIR"]}
    out["macro"]["max_within_scenario_range"] = {
        ds: float(max(out["scenarios"][s][ds]["range"] for s in SCENARIOS
                      if out["scenarios"][s][ds]["range"] is not None))
        for ds in ["DIV2K", "LSDIR"]}

    jp = E6A / "e6a_summary.json"
    json.dump(out, open(jp, "w"), indent=2, ensure_ascii=False)

    lines = ["# E6-A agent run-to-run variance (fixed support / training seed)",
             "",
             "6 scenarios x 3 independent agent blind-ID repetitions, R0-only training "
             "(Swin+SG, Direct, 2 epochs, seed 42, same 5 support pairs).",
             "Test: GT-LQ DIV2K 100 / LSDIR 250 (same protocol as E6-B).",
             "",
             "| Scenario | GT pipeline | rep1 | rep2 | rep3 | mean | SD | range | exact GT | E6-B set1 |",
             "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for sid in SCENARIOS:
        r = out["scenarios"][sid]
        vals = [r["reps"].get(f"rep{i}", {}) or {} for i in [1, 2, 3]]
        cell = [f"{v['DIV2K']:.3f}" if v.get("DIV2K") is not None else "-" for v in vals]
        gt_str = " + ".join(f"{f}:{s}" for f, s in r["gt_pipeline"])
        lines.append(f"| {sid} | {gt_str} | {cell[0]} | {cell[1]} | {cell[2]} | "
                     f"{r['DIV2K']['mean']:.3f} | {r['DIV2K']['sd']:.3f} | "
                     f"{r['DIV2K']['range']:.3f} | {r['exact_gt_matches']}/3 | "
                     f"{r['e6b_set1_DIV2K']:.3f} |")
    m = out["macro"]["DIV2K"]
    lines += ["",
              f"Macro (mean of scenario means, DIV2K): {m['mean_of_scenario_means']:.3f} dB; "
              f"between-scenario SD {m['scenario_sd']:.3f}; "
              f"mean within-scenario SD {out['macro']['mean_within_scenario_sd']['DIV2K']:.3f} dB; "
              f"max within-scenario range {out['macro']['max_within_scenario_range']['DIV2K']:.3f} dB.",
              ""]
    (E6A / "e6a_summary.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
